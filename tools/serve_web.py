#!/usr/bin/env python3
"""Serve the web build locally with the cross-origin isolation headers Godot's
threaded web runtime needs (SharedArrayBuffer), and no caching while testing.

Usage:
    python serve_web.py [port] [--https]

--https serves TLS with the self-signed certificate in ../certs/server.pem
(generated by make_cert.py). iOS Safari only grants SharedArrayBuffer to
secure contexts, so the iPad needs the https URL; accept the self-signed
certificate warning once when the page first loads.
"""
import http.server
import os
import socketserver
import ssl
import sys

PORT = int(sys.argv[1]) if len(sys.argv) > 1 and sys.argv[1].isdigit() else 8124
USE_HTTPS = "--https" in sys.argv
ROOT = os.path.dirname(os.path.abspath(__file__))
WEB = os.path.join(ROOT, "..", "web")


class Handler(http.server.SimpleHTTPRequestHandler):
    def __init__(self, *a, **kw):
        super().__init__(*a, directory=WEB, **kw)

    def end_headers(self):
        self.send_header("Cross-Origin-Opener-Policy", "same-origin")
        self.send_header("Cross-Origin-Embedder-Policy", "require-corp")
        self.send_header("Cross-Origin-Resource-Policy", "cross-origin")
        self.send_header("Cache-Control", "no-store, no-cache, must-revalidate, max-age=0")
        self.send_header("Service-Worker-Allowed", "/")
        super().end_headers()

    def log_message(self, fmt, *args):
        sys.stderr.write("%s - %s\n" % (self.address_string(), fmt % args))


class Server(socketserver.ThreadingTCPServer):
    allow_reuse_address = True
    daemon_threads = True


if __name__ == "__main__":
    os.chdir(WEB)
    scheme = "http"
    if USE_HTTPS:
        cert = os.path.join(ROOT, "..", "certs", "server.pem")
        key = os.path.join(ROOT, "..", "certs", "server.key")
        if not (os.path.exists(cert) and os.path.exists(key)):
            print("https requested but certs missing - run: python webport/tools/make_cert.py")
            sys.exit(1)
        ctx = ssl.SSLContext(ssl.PROTOCOL_TLS_SERVER)
        ctx.load_cert_chain(cert, key)
        httpd.socket = ctx.wrap_socket(httpd.socket, server_side=True)
        scheme = "https"
    url = f"{scheme}://127.0.0.1:{PORT}/"
    if scheme == "https":
        import socket
        try:
            lan_ip = socket.gethostbyname(socket.gethostname())
            url = f"{scheme}://{lan_ip}:{PORT}/   (iPad: open this and accept the certificate warning)"
        except OSError:
            pass
    print(f"serving {os.path.abspath(WEB)} on {url}")
    with Server(("0.0.0.0", PORT), Handler) as httpd:
        httpd.serve_forever()
